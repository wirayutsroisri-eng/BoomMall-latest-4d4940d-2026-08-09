import type { BoardSide, FeedItem, FeedLane, FeedProduct } from '../domain/types';
import { CHANTHABURI, offsetKm } from '@/modules/matching/domain/geo';
import type { SearchRadiusOption } from '@/modules/matching/domain/search-radius';

type Draft = {
  id: string;
  lane: FeedLane;
  author: string;
  handle: string;
  caption: string;
  location: string;
  likes: number;
  comments: number;
  shares: number;
  isLive?: boolean;
  music: string;
  gradient: [string, string];
  seed: string;
  productName: string;
  shopName: string;
  tier: FeedProduct['tier'];
  price: number;
  tags: string[];
  boardSide?: BoardSide;
  gps?: { lat: number; lng: number };
  searchRadius?: SearchRadiusOption;
  /** Skip remote image — use gradient + category glyph on board tiles */
  noImage?: boolean;
  imageW?: number;
  imageH?: number;
};

function productOf(d: Draft): FeedProduct {
  return {
    id: `p-${d.id}`,
    name: d.productName,
    shopName: d.shopName,
    tier: d.tier,
    basePrice: d.price,
    currency: 'THB',
    tags: d.tags,
    variants: [
      {
        id: `v-${d.id}-1`,
        label: 'มาตรฐาน',
        price: d.price,
        stock: 12 + (d.likes % 40),
      },
      {
        id: `v-${d.id}-2`,
        label: 'พรีเมียม',
        price: Math.round(d.price * 1.18),
        stock: 4 + (d.comments % 10),
      },
    ],
  };
}

function toItem(d: Draft): FeedItem {
  const imageWidth = d.noImage ? undefined : d.imageW ?? 1080;
  const imageHeight = d.noImage ? undefined : d.imageH ?? 1920;
  return {
    id: d.id,
    lane: d.lane,
    boardSide: d.boardSide,
    author: d.author,
    authorHandle: d.handle.startsWith('@') ? d.handle : `@${d.handle}`,
    caption: d.caption,
    location: d.location,
    gps: d.gps,
    searchRadius: d.searchRadius,
    likes: d.likes,
    comments: d.comments,
    shares: d.shares,
    isLive: Boolean(d.isLive),
    musicTitle: d.music,
    gradient: d.gradient,
    imageUri: d.noImage ? undefined : `https://picsum.photos/seed/${d.seed}/${imageWidth}/${imageHeight}`,
    imageWidth,
    imageHeight,
    product: productOf(d),
  };
}

